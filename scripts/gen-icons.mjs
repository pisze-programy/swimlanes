// Generate src/core/icons.generated.ts from the Font Awesome free metadata.
// Run: npm run icons
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const metadataPath = resolve(
  root,
  "node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json",
);
const outPath = resolve(root, "src/core/icons.generated.ts");

const families = JSON.parse(readFileSync(metadataPath, "utf8"));

/** @param {unknown} entry */
function freeStyles(entry) {
  const result = { solid: false, regular: false, brand: false };
  const byLicense = entry.familyStylesByLicense;
  if (typeof byLicense !== "object" || byLicense === null) {
    return result;
  }
  const free = byLicense.free;
  if (!Array.isArray(free)) {
    return result;
  }
  for (const item of free) {
    if (typeof item !== "object" || item === null) {
      continue;
    }
    if (item.family === "classic" && item.style === "solid") {
      result.solid = true;
    }
    if (item.family === "classic" && item.style === "regular") {
      result.regular = true;
    }
    if (item.style === "brands") {
      result.brand = true;
    }
  }
  return result;
}

const rows = [];
for (const [name, entry] of Object.entries(families)) {
  if (typeof entry !== "object" || entry === null) {
    continue;
  }
  const unicode = entry.unicode;
  if (typeof unicode !== "string") {
    continue;
  }
  const styles = freeStyles(entry);
  if (!styles.solid && !styles.regular && !styles.brand) {
    continue;
  }
  const names = [name];
  const aliases = entry.aliases;
  if (typeof aliases === "object" && aliases !== null && Array.isArray(aliases.names)) {
    for (const alias of aliases.names) {
      if (typeof alias === "string") {
        names.push(alias);
      }
    }
  }
  for (const candidate of names) {
    rows.push([candidate, unicode, styles.solid, styles.regular, styles.brand]);
  }
}

rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const lines = [];
lines.push("// Generated by scripts/gen-icons.mjs. Do not edit by hand.");
lines.push("// Source: @fortawesome/fontawesome-free (SIL OFL 1.1).");
lines.push('import type { IconGlyph } from "./icons";');
lines.push("");
lines.push("export const iconGlyphs: ReadonlyMap<string, IconGlyph> = new Map([");
for (const [name, unicode, solid, regular, brand] of rows) {
  lines.push(
    `  ["${name}", { unicode: "${unicode}", solid: ${solid}, regular: ${regular}, brand: ${brand} }],`,
  );
}
lines.push("]);");
lines.push("");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join("\n"), "utf8");

console.log(`wrote ${rows.length} icon names to ${outPath}`);
